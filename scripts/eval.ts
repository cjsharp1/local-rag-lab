/**
 * eval.ts — the scorecard (PLAN §8). Code scores everything; no model judges.
 *
 * Run it with:  npm run eval -- --check       check the question set against the corpus
 *               npm run eval -- --retrieval   the retrieval pass (needs Ollama, no chat model)
 *
 * The retrieval pass (scripts/eval-retrieval.ts) measures, for each
 * question and each of 27 search configurations, whether the gold spans
 * came back (hit@k, partial, MRR), and writes docs/scorecard.md.
 *
 * Coming at build step 9: the answer pass and the rerank pass, with the
 * chat model.
 *
 * --check is the fast one, and the one to run after editing any document
 * or question. It loads the 30 question files (server/questions.ts),
 * validates their shape, and checks every gold span, required fact and
 * forbidden fact against the corpus. It needs no model and no index. If
 * it passes, every expected answer the scorecard uses is at least
 * present, word for word, in the documents it claims to come from.
 */

import "dotenv/config";

import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

import { checkQuestions, loadQuestions, QuestionFileError } from "../server/questions.js";
import { DEFAULT_SEARCH } from "../shared/search-settings.js";
import { corpusHash, loadCorpus } from "../tool-server/corpus.js";
import { EmbedError } from "../tool-server/embed.js";
import { printRetrieval, renderRetrieval, runRetrievalPass } from "./eval-retrieval.js";

const SCORECARD = join(fileURLToPath(new URL(".", import.meta.url)), "..", "docs", "scorecard.md");

function check(): void {
  let questions;
  try {
    questions = loadQuestions();
  } catch (error: unknown) {
    if (error instanceof QuestionFileError) {
      console.error(`\n${error.message}\n`);
      process.exit(1);
    }
    throw error;
  }

  const docs = loadCorpus();
  const problems = checkQuestions(questions, docs);
  const spans = questions.reduce((n, q) => n + q.hops.flat().length, 0);

  if (problems.length > 0) {
    console.error(`\n${questions.length} questions, ${problems.length} problem${problems.length === 1 ? "" : "s"}:\n`);
    for (const p of problems) console.error(`  ${p}`);
    console.error("");
    process.exit(1);
  }
  console.log(`\n${questions.length} questions, all spans found (${spans} gold spans in ${docs.length} documents; ` +
    "every required fact is in its own gold text, every forbidden fact is in the corpus and not in its gold text).\n");
}

/** The retrieval pass: build nine indexes, search, score, write docs/scorecard.md. */
async function retrieval(): Promise<void> {
  const questions = loadQuestions();
  const docs = loadCorpus();
  const problems = checkQuestions(questions, docs);
  if (problems.length > 0) {
    console.error(`\nThe question set has problems; run  npm run eval -- --check  first.\n`);
    process.exit(1);
  }

  console.log("\nRetrieval pass: building 9 indexes (3 strategies × 3 presets) and searching with each question.\n");
  let report;
  try {
    report = await runRetrievalPass(questions, docs, corpusHash(docs), (line) => console.log(line));
  } catch (error: unknown) {
    if (error instanceof EmbedError) {
      console.error(`\n${error.message}\n`);
      process.exit(1);
    }
    throw error;
  }
  printRetrieval(report);

  const header = [
    "# Scorecard",
    "",
    "Generated by `npm run eval`. Do not edit by hand; rerun it.",
    "",
    `Corpus ${corpusHash(docs).slice(0, 12)}…, ${docs.length} documents, ${questions.length} questions. ` +
      `Embeddings: ${process.env.EMBED_MODEL || "nomic-embed-text"}. Search defaults: ${DEFAULT_SEARCH.mode} mode, ` +
      `top-k ${DEFAULT_SEARCH.topK}, floor ${DEFAULT_SEARCH.floor}.`,
    "",
  ].join("\n");
  const answers = "## Answer pass\n\nNot run yet: the answer pass and the rerank pass arrive at build step 9.\n";
  writeFileSync(SCORECARD, `${header}\n${renderRetrieval(report, questions)}\n${answers}`);
  console.log(`\nWrote ${SCORECARD.replace(/\\/g, "/").split("/").slice(-2).join("/")}.\n`);
}

if (process.argv.includes("--check")) {
  check();
} else if (process.argv.includes("--retrieval")) {
  await retrieval();
} else {
  console.error("\nUsage:  npm run eval -- --check        check the question set against the corpus");
  console.error("        npm run eval -- --retrieval    the retrieval pass (needs Ollama)");
  console.error("The answer pass arrives at build step 9.\n");
  process.exit(1);
}
